#!/usr/bin/env python3
"""Bake a white-on-transparent icon PNG into an 8-bit coverage table for the shim.

WHY THIS EXISTS, and it is bake_menu_font.py's reason one surface over. The
SETTINGS column in the swipe-down band (menu_zone.c's MZ_COLS'th) is drawn as a
mark rather than as its label, because a gear is not a word. menu_paint.c first
DREW one -- a body disc, eight teeth and a hub punched through, all in integer
arithmetic because the shim is a soft-float build -- and it took five attempts on
the bench and the glass to get a shape that read as a gear at all: teeth too wide
read as a flower, teeth clipped by a rim circle left one-pixel spikes and isolated
pixels, a thick ring read as a cross, thin long teeth read as a sun, and the first
working shape was simply "too thick".

The operator's answer was this file's reason: *"how about just using
gear_white100.png"* -- a drawn icon, antialiased, with curves no per-pixel integer
predicate is going to produce at 30 px.

THE SHIM GETS A TABLE, NOT A DECODER, which is the same trade the font makes: no
PNG decoder, no libpng, no file I/O and no scaler in the shim -- it gets an array
of bytes. The bake runs once, on a machine, and its output is committed.

    python3 scripts/shims/bake_gear.py [px]

The output is scripts/shims/gear_icon.h. `px` defaults to DEFAULT_PX below, which
is the size the operator chose -- it is baked AT the size it is drawn at, 1:1, for
the same reason the atlas is ("there is no scale parameter anywhere in this
interface, because a scaled bitmap is what this file exists to stop doing").
menu_paint.c refuses a band too short to host the icon whole, so a panel small
enough to need a smaller mark refuses the band rather than shrinking the mark.

THE COVERAGE IS THE SOURCE'S ALPHA CHANNEL. The icon is white on transparent, so
alpha is ink, and it is the same 0..255 coverage the atlas carries: 0 is "the
button's face" and 255 is "the label colour", with only the edges blending -- which
is what keeps menu_paint.c's "painting it twice paints it once" true.
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DEFAULT_SRC = os.path.join(HERE, "gear_white100.png")
OUT = os.path.join(HERE, "gear_icon.h")
# THE SIZES BAKED, smallest first, and why there is more than one. The mark is drawn 1:1
# (no scaler in the shim), so it has to fit the band WHOLE with two rows to spare -- the
# marks are drawn over the button's outline rows and a damage-witness point samples exactly
# those, so an icon that touched them would read as damage on every tick. The band is
# 56 rows of the 800-row logical panel scaled, which gives 40 rows at 1280x800 but only 24
# at 800x480 -- a shape this port supports and refuses to lose. Hence a small bake for a
# short band and a full one for a tall band; menu_paint.c picks the largest that fits, and a
# band too short for the smallest refuses the panel (which is what a 640-wide panel already
# does, one surface along).
DEFAULT_PX = (22, 30)


def bake(src, px):
    """(w, h, bytes) -- the icon's alpha, resized to `px` and read as coverage."""
    im = Image.open(src).convert("RGBA")
    # LANCZOS and not NEAREST: the whole point of using a drawn icon is its curves,
    # and a nearest-neighbour downscale would put the hard edges straight back.
    im = im.resize((px, px), Image.LANCZOS)
    alpha = im.getchannel("A")
    return px, px, bytes(alpha.tobytes())


def hexdump(data, per_line=16):
    out = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        out.append("    " + " ".join("0x%02x," % b for b in chunk))
    return "\n".join(out)


HEADER = '''/*
 * gear_icon.h -- the SETTINGS column's mark. GENERATED.
 *
 * Do not edit this file. It is written by scripts/shims/bake_gear.py, which reads
 * %(srcrel)s -- a white-on-transparent gear, %(srcpx)d px square -- and resizes it to
 * several times -- at %(px)s px -- because the mark is drawn 1:1 and the band's height
 * depends on the panel: menu_paint.c blits the largest bake that fits the band, centred in
 * the button. To change the sizes, the source or the icon, run
 *
 *     python3 scripts/shims/bake_gear.py --px %(px)s
 *     python3 scripts/shims/bake_gear.py --src <file.png>
 *
 * WHY A BAKED TABLE AND NOT A DRAWN SHAPE, which is what menu_paint.c did first.
 * The mark began as geometry -- a disc, eight teeth and a hub, in integer arithmetic
 * because the shim is a soft-float build -- and it took five attempts on the bench and
 * the glass to get a shape that read as a gear: teeth 68%% of their pitch merged into a
 * flower; narrower teeth clipped by a rim circle tapered to ONE-PIXEL SPIKES and left
 * ISOLATED PIXELS off their tips ("it has some weird look at the top, bottom, left and
 * right"); a thick ring with teeth the same depth read as a cross; thin teeth on a thin
 * ring read as a sun; and the first shape that worked at all was, in the operator's two
 * words, "too thick". The operator's answer was this file: *"how about just using
 * gear_white100.png"*. A drawn icon carries curves and antialiasing that no per-pixel
 * predicate is going to produce at 30 px.
 *
 * THE SHIM GETS A TABLE, NOT A DECODER -- the same trade menu_font.h makes. There is no
 * PNG decoder, no libpng, no scaler and no file I/O in the shim; the bake runs once, on a
 * machine, and its output is committed.
 *
 * ONE BYTE PER PIXEL, ROW MAJOR, TOP ROW FIRST, and the value is the SOURCE'S ALPHA: 0 is
 * "the button's face" and 255 is "the label colour", with only the edges blending -- the
 * same 0..255 coverage the atlas carries, which is what keeps menu_paint.c's "painting it
 * twice paints it once" true and lets the mark dim with a dim row (menu_paint.c passes the
 * row's own ink as the blend's ink, so a refused row's gear is drawn in the OFF colour).
 *
 * THE ICON IS CENTRED AND DRAWN 1:1, and a band too short to host it whole is REFUSED
 * rather than scaled (menu_paint.c's menu_labels_fit()). That is the atlas's own rule: a
 * scaled bitmap is what this tree bakes tables to avoid.
 */
#ifndef RBPI4B_GEAR_ICON_H
#define RBPI4B_GEAR_ICON_H

#define GEAR_ICON_SIZES %(n)d

/* One baked size. menu_paint.c picks the LARGEST whose `h` fits the band with two rows to
 * spare, so a tall panel gets the full mark and a short one gets a smaller mark rather than
 * a refused band. */
struct gear_icon {
    int w, h;
    const unsigned char *cov;    /* row major, top row first, one byte per pixel */
};

%(tables)s
static const struct gear_icon gear_icons[GEAR_ICON_SIZES] = {
%(pick)s
};

#endif /* RBPI4B_GEAR_ICON_H */
'''


def main(argv):
    src = DEFAULT_SRC
    px = DEFAULT_PX
    i = 1
    while i < len(argv):
        a = argv[i]
        if a == "--src" and i + 1 < len(argv):
            i += 1
            src = argv[i]
        elif a == "--px" and i + 1 < len(argv):
            i += 1
            px = tuple(int(v) for v in argv[i].split(","))
        elif a in ("-h", "--help"):
            print(__doc__)
            return 0
        else:
            print("bake_gear: unknown argument %r" % a, file=sys.stderr)
            return 2
        i += 1

    if not os.path.exists(src):
        print("bake_gear: no such source %s" % src, file=sys.stderr)
        return 1

    sizes = px if isinstance(px, (list, tuple)) else (px,)
    tables, pick = [], []
    for i, s_px in enumerate(sizes):
        w, h, data = bake(src, s_px)
        # A coverage that is all zero is a mark that draws nothing -- a column that looks
        # broken on the glass -- which is what a mis-read alpha channel produces.
        lo, hi = min(data), max(data)
        if hi == 0:
            print("bake_gear: %s baked to nothing at %d px -- is its alpha empty?"
                  % (src, s_px), file=sys.stderr)
            return 1
        tables.append(
            "static const unsigned char gear_icon_cov_%d[%d * %d] = {\n%s\n};\n"
            % (i, w, h, hexdump(data)))
        pick.append("    { %d, %d, gear_icon_cov_%d }," % (w, h, i))
        print("bake_gear: %s at %d px -> %dx%d, coverage %d..%d"
              % (os.path.relpath(src, REPO), s_px, w, h, lo, hi))

    with open(OUT, "w") as f:
        f.write(HEADER % {
            "srcrel": os.path.relpath(src, REPO),
            "srcpx": Image.open(src).width,
            "px": ", ".join(str(x) for x in sizes),
            "n": len(sizes),
            "tables": "\n".join(tables),
            "pick": "\n".join(pick),
        })
    print("bake_gear: wrote %s (%d size(s))" % (os.path.relpath(OUT, REPO), len(sizes)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
